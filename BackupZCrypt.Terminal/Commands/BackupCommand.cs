    private async Task ExecutePlainCopyAsync(
        string operationName,
        string sourcePath,
        string destinationPath
    )
    {
        AnsiConsole.WriteLine();

        using CancellationTokenSource cts = new();

        ConsoleCancelEventHandler cancelHandler = (_, e) =>
        {
            e.Cancel = true;
            cts.Cancel();
            AnsiConsole.MarkupLine($"[yellow]{Messages.Cancelling}[/]");
        };

        Console.CancelKeyPress += cancelHandler;

        try
        {
            var sw = Stopwatch.StartNew();
            List<string> errors = [];
            var processedFiles = 0;
            long totalBytes = 0;
            int totalFileCount;

            if (Directory.Exists(sourcePath))
            {
                if (Directory.Exists(destinationPath))
                {
                    Directory.Delete(destinationPath, recursive: true);
                    Directory.CreateDirectory(destinationPath);
                }

                var files = Directory.GetFiles(sourcePath, "*", SearchOption.AllDirectories);
                totalFileCount = files.Length;

                await AnsiConsole
                    .Progress()
                    .AutoClear(false)
                    .HideCompleted(false)
                    .Columns(
                        new TaskDescriptionColumn(),
                        new ProgressBarColumn(),
                        new PercentageColumn(),
                        new RemainingTimeColumn(),
                        new SpinnerColumn()
                    )
                    .StartAsync(async ctx =>
                    {
                        var task = ctx.AddTask(
                            $"[cyan]{string.Format(Messages.OperationIngFormat, Messages.Copying)}[/]",
                            maxValue: Math.Max(totalFileCount, 1)
                        );

                        foreach (var file in files)
                        {
                            cts.Token.ThrowIfCancellationRequested();

                            var relativePath = Path.GetRelativePath(sourcePath, file);
                            var destFile = Path.Combine(destinationPath, relativePath);
                            var destDir = Path.GetDirectoryName(destFile);

                            if (destDir is not null)
                            {
                                Directory.CreateDirectory(destDir);
                            }

                            try
                            {
                                await using FileStream sourceStream = new(
                                    file,
                                    FileMode.Open,
                                    FileAccess.Read,
                                    FileShare.Read,
                                    4096,
                                    useAsync: true
                                );
                                await using FileStream destStream = new(
                                    destFile,
                                    FileMode.Create,
                                    FileAccess.Write,
                                    FileShare.None,
                                    4096,
                                    useAsync: true
                                );
                                await sourceStream.CopyToAsync(destStream, cts.Token);

                                totalBytes += new FileInfo(file).Length;
                                processedFiles++;
                            }
                            catch (Exception ex) when (ex is not OperationCanceledException)
                            {
                                errors.Add($"{relativePath}: {ex.Message}");
                            }

                            task.Value = processedFiles + errors.Count;
                            task.Description =
                                $"[cyan]{string.Format(Messages.OperationIngFilesFormat, Messages.Copying, processedFiles, totalFileCount)}[/]";
                        }
                    });
            }
            else
            {
                totalFileCount = 1;

                await AnsiConsole
                    .Progress()
                    .AutoClear(false)
                    .HideCompleted(false)
                    .Columns(
                        new TaskDescriptionColumn(),
                        new ProgressBarColumn(),
                        new PercentageColumn(),
                        new SpinnerColumn()
                    )
                    .StartAsync(async ctx =>
                    {
                        var task = ctx.AddTask(
                            $"[cyan]{string.Format(Messages.OperationIngFormat, Messages.Copying)}[/]",
                            maxValue: 1
                        );

                        string destFile;

                        if (Directory.Exists(destinationPath))
                        {
                            destFile = Path.Combine(destinationPath, Path.GetFileName(sourcePath));
                        }
                        else
                        {
                            var destDir = Path.GetDirectoryName(destinationPath);

                            if (destDir is not null)
                            {
                                Directory.CreateDirectory(destDir);
                            }

                            destFile = destinationPath;
                        }

                        try
                        {
                            await using FileStream sourceStream = new(
                                sourcePath,
                                FileMode.Open,
                                FileAccess.Read,
                                FileShare.Read,
                                4096,
                                useAsync: true
                            );
                            await using FileStream destStream = new(
                                destFile,
                                FileMode.Create,
                                FileAccess.Write,
                                FileShare.None,
                                4096,
                                useAsync: true
                            );
                            await sourceStream.CopyToAsync(destStream, cts.Token);

                            totalBytes = new FileInfo(sourcePath).Length;
                            processedFiles = 1;
                        }
                        catch (Exception ex) when (ex is not OperationCanceledException)
                        {
                            errors.Add(ex.Message);
                        }

                        task.Value = 1;
                    });
            }

            sw.Stop();

            if (errors.Count == 0 && processedFiles > 0)
            {
                List<ManifestEntry> entries = [];
                string manifestDir;

                if (Directory.Exists(sourcePath))
                {
                    manifestDir = destinationPath;
                    var files = Directory.GetFiles(
                        destinationPath,
                        "*",
                        SearchOption.AllDirectories
                    );

                    foreach (var file in files)
                    {
                        var relativePath = Path.GetRelativePath(destinationPath, file);
                        entries.Add(
                            new ManifestEntry(
                                relativePath,
                                relativePath,
                                string.Empty,
                                string.Empty,
                                string.Empty
                            )
                        );
                    }
                }
                else
                {
                    var destFile = Directory.Exists(destinationPath)
                        ? Path.Combine(destinationPath, Path.GetFileName(sourcePath))
                        : destinationPath;
                    manifestDir = Path.GetDirectoryName(destFile) ?? destinationPath;
                    var fileName = Path.GetFileName(destFile);
                    entries.Add(
                        new ManifestEntry(
                            fileName,
                            fileName,
                            string.Empty,
                            string.Empty,
                            string.Empty
                        )
                    );
                }

                ManifestHeader header = new(default, default, CompressionMode.None);

                await manifestService.TrySavePlainManifestAsync(
                    entries,
                    header,
                    manifestDir,
                    cts.Token
                );
            }

            BackupResult result = new(
                errors.Count == 0,
                sw.Elapsed,
                totalBytes,
                processedFiles,
                totalFileCount,
                errors,
                []
            );

            ResultRenderer.Print(result, operationName);
        }
        catch (OperationCanceledException)
        {
            AnsiConsole.MarkupLine($"[yellow]{Messages.OperationCancelledByUser}[/]");
        }
        catch (Exception ex)
        {
            AnsiConsole.MarkupLine(
                $"[red]{string.Format(Messages.UnexpectedErrorFormat, Markup.Escape(ex.Message))}[/]"
            );
        }
        finally
        {
            Console.CancelKeyPress -= cancelHandler;
        }
    }

