        {
            e.Cancel = true;
            cts.Cancel();
            AnsiConsole.MarkupLine($"[yellow]{Messages.Cancelling}[/]");
        };

        Console.CancelKeyPress += cancelHandler;

        try
        {
            var sw = Stopwatch.StartNew();
            List<string> errors = [];
